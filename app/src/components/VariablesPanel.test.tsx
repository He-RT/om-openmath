import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { expect, test, vi } from 'vitest';
import { VariablesPanel } from './VariablesPanel';
import { NotebookController, type UiCell } from '../state/notebookStore';
import { MockKernel } from '../test/mockKernel';
import { messages } from '../i18n';
import type { Response } from '../kernel/client';
const cell: UiCell = { id: 'definition', source: 'let a=2', dialect: 'Modern', kind: 'Math', revision: 1,
  status: 'Done', exec_count: 1, defines: ['a'], uses: [], resultSource: { source: 'let a=2', dialect: 'Modern' } };
const t = messages('en');
test('accepted values retain source IDs, stale drafts do not fetch on every keystroke, and undefined names come from kernel facts', async () => {
  const kernel = new MockKernel(() => ({ type: 'variables', items: [['a', { value: '2', cell_id: cell.id, signature: null, summary: '', examples: [] }]] }));
  const controller = new NotebookController(kernel), select = vi.spyOn(controller, 'select');
  const props = { cells: [cell], controller, generation: 1, busy: false, language: 'en', t, phone: true };
  const view = render(<VariablesPanel {...props} />);
  expect(await screen.findByRole('row', { name: 'a 2 Cell 1' })).toBeTruthy();
  const stale = { ...cell, source: 'let a=5', status: 'Stale' as const };
  view.rerender(<VariablesPanel {...props} cells={[stale]} />);
  expect(await screen.findByText('Out of date')).toBeTruthy();
  await waitFor(() => expect(kernel.requests).toHaveLength(2));
  view.rerender(<VariablesPanel {...props} cells={[{ ...stale, source: 'let a=6' }]} />);
  expect(kernel.requests).toHaveLength(2);
  fireEvent.keyDown(screen.getByRole('row', { name: 'a 2 Out of date Cell 1' }), { key: 'Enter' });
  expect(select).toHaveBeenCalledWith(cell.id);
  expect(controller.store.getState().panel).toBeNull();
  view.rerender(<VariablesPanel {...props} cells={[cell, { ...cell, id: 'broken', defines: ['f'], status: 'Error' }]} />);
  expect(await screen.findByRole('row', { name: 'f Undefined, cell has an error Cell 2' })).toBeTruthy();
  controller.dispose();
});
test('late reads from a replaced owner are ignored; a failed read keeps values and exposes retry', async () => {
  const completions: ((response: Response) => void)[] = [];
  const kernel = new MockKernel(() => new Promise(resolve => completions.push(resolve)));
  const controller = new NotebookController(kernel);
  const props = { cells: [cell], controller, generation: 1, busy: false, language: 'en', t, phone: false };
  const view = render(<VariablesPanel {...props} />);
  view.rerender(<VariablesPanel {...props} language="zh-CN" />);
  await act(async () => completions[1]!({ type: 'variables', items: [['current', { value: '3', cell_id: cell.id, signature: null, summary: '', examples: [] }]] }));
  await act(async () => completions[0]!({ type: 'variables', items: [['old', { value: '2', cell_id: cell.id, signature: null, summary: '', examples: [] }]] }));
  expect(screen.queryByText('old')).toBeNull();
  view.rerender(<VariablesPanel {...props} language="zh-CN" cells={[{ ...cell, defines: ['f'], status: 'Error' }]} />);
  expect(screen.queryByText('Undefined, cell has an error')).toBeNull();
  await act(async () => completions[2]!({ type: 'error', message: 'Disconnected' }));
  expect(screen.getByRole('alert').textContent).toContain('Disconnected');
  expect(screen.getByText('current')).toBeTruthy();
  expect(screen.queryByText('Undefined, cell has an error')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
  await act(async () => completions[3]!({ type: 'variables', items: [] }));
  expect(screen.queryByText('current')).toBeNull();
  expect(screen.queryByRole('alert')).toBeNull(); controller.dispose();
  expect(screen.getByRole('row', { name: 'f Undefined, cell has an error Cell 1' })).toBeTruthy();
});
