import type { Language } from "../kernel/generated/Language";
export type Locale = "zh-CN" | "en";
export function locale(
  language: Language = "auto",
  system = navigator.language,
): Locale {
  return language === "auto"
    ? system.toLowerCase().startsWith("zh")
      ? "zh-CN"
      : "en"
    : language;
}
