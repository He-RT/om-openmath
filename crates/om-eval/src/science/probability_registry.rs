//! Executable special-function and distribution registrations; defaults live in the shared catalog.
use crate::{Arity, Attributes as A, BuiltinSpec, DocEntry, EvalError, Evaluator};
use om_core::{Expr, Interrupt, Symbol};
use std::collections::BTreeMap;
pub(super) fn register(specs: &mut BTreeMap<&'static str, BuiltinSpec>) {
    macro_rules! entry {($f:ident,$name:literal,$arity:expr,$attrs:expr,$modern:literal,$wolfram:literal,$summary:literal,$example:literal)=>{
        fn $f(ev:&mut Evaluator,args:&[Expr],ctx:&Interrupt)->Result<Option<Expr>,EvalError>{super::dispatch(ev,$name,args,ctx)}
        specs.insert($name,BuiltinSpec{symbol:Symbol::intern($name),f:$f,attrs:$attrs|A::PROTECTED,arity:$arity,doc:DocEntry{name:$name,modern:$modern,wolfram:$wolfram,summary_zh:$summary,summary_en:"Real special functions, validated distributions and deterministic random streams within documented precision limits.",examples:&[$example],category:"Scientific"}});
    };}
    let numeric = A::LISTABLE | A::NUMERIC_FUNCTION;
    entry!(
        erf,
        "Erf",
        Arity::Exactly(1),
        numeric,
        "erf(x)",
        "Erf[x]",
        "实数误差函数，机器路径与精确零值。",
        "Erf[1.]"
    );
    entry!(
        erfc,
        "Erfc",
        Arity::Exactly(1),
        numeric,
        "erfc(x)",
        "Erfc[x]",
        "直接计算互补误差函数尾部。",
        "Erfc[8.]"
    );
    entry!(
        gamma,
        "Gamma",
        Arity::Exactly(1),
        numeric,
        "gamma(x)",
        "Gamma[x]",
        "正实Gamma；正整数精确阶乘关系。",
        "Gamma[5]"
    );
    entry!(
        log_gamma,
        "LogGamma",
        Arity::Exactly(1),
        numeric,
        "log_gamma(x)",
        "LogGamma[x]",
        "正实机器LogGamma，溢出明确失败。",
        "LogGamma[1000.]"
    );
    entry!(
        beta,
        "Beta",
        Arity::Exactly(2),
        numeric,
        "beta(a,b)",
        "Beta[a,b]",
        "正实机器Beta。",
        "Beta[2.,3.]"
    );
    entry!(
        acoth,
        "ArcCoth",
        Arity::Exactly(1),
        numeric,
        "acoth(x)",
        "ArcCoth[x]",
        "实数主值反双曲余切；要求|x|>1。",
        "ArcCoth[2.]"
    );
    entry!(
        asech,
        "ArcSech",
        Arity::Exactly(1),
        numeric,
        "asech(x)",
        "ArcSech[x]",
        "实数主值反双曲正割；要求0<x≤1。",
        "ArcSech[0.5]"
    );
    entry!(
        acsch,
        "ArcCsch",
        Arity::Exactly(1),
        numeric,
        "acsch(x)",
        "ArcCsch[x]",
        "实数主值反双曲余割；要求x≠0。",
        "ArcCsch[2.]"
    );
    entry!(
        normal,
        "NormalDistribution",
        Arity::Range(0, 4),
        A::default(),
        "normal_distribution(mean:0,std:1)",
        "NormalDistribution[mean,std]",
        "经校验的正态分布对象。",
        "NormalDistribution[0,1]"
    );
    entry!(
        uniform,
        "UniformDistribution",
        Arity::Range(0, 2),
        A::default(),
        "uniform_distribution(bounds:[0,1])",
        "UniformDistribution[bounds]",
        "经校验的连续均匀分布对象。",
        "UniformDistribution[{0,1}]"
    );
    entry!(
        pdf,
        "PDF",
        Arity::Exactly(2),
        A::default(),
        "pdf(distribution,value)",
        "PDF[distribution,value]",
        "正态/均匀分布密度。",
        "PDF[NormalDistribution[0,1],0]"
    );
    entry!(
        cdf,
        "CDF",
        Arity::Exactly(2),
        A::default(),
        "cdf(distribution,value)",
        "CDF[distribution,value]",
        "正态/均匀累积分布，尾部不以1-erf相减。",
        "CDF[NormalDistribution[0,1],0]"
    );
    entry!(
        uniform_rng,
        "RandomUniform",
        Arity::Range(0, 3),
        A::default(),
        "random_uniform(count:1,bounds:[0,1])",
        "RandomUniform[Count->1]",
        "SplitMix64可重复半开范围均匀采样。",
        "RandomUniform[Count->3,Seed->42]"
    );
    entry!(
        normal_rng,
        "RandomNormal",
        Arity::Range(0, 4),
        A::default(),
        "random_normal(count:1,mean:0,std:1)",
        "RandomNormal[Count->1]",
        "Box–Muller正态采样，显式种子隔离会话状态。",
        "RandomNormal[Count->3,Seed->42]"
    );
    entry!(
        choice,
        "RandomChoice",
        Arity::Range(1, 3),
        A::default(),
        "random_choice(data,count:1)",
        "RandomChoice[data]",
        "无偏索引的有放回随机选择。",
        "RandomChoice[{1,2},Count->3,Seed->42]"
    );
    entry!(
        seed,
        "SeedRandom",
        Arity::Exactly(1),
        A::default(),
        "seed_random(seed)",
        "SeedRandom[seed]",
        "设置会话种子；只读计算拒绝修改。",
        "SeedRandom[42]"
    );
}
