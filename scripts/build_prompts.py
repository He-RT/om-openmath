#!/usr/bin/env python3
"""Assemble the notebook assistant system prompt from its source layers.

Sources: agent/prompts/*.zh.md and the "模型操作说明" section of
docs/design/prompts/notebook-operation.md (read, never modified: it is a frozen design source).
Outputs (all derived, committed so drift is visible in review):
  agent/prompts/generated/system.zh.md            readable template
  agent/prompts/generated/prompt.json             template, mode lines, hash, size (Web consumes this)
  macos/OpenMathNative/Agent/SystemPromptText.swift

  python3 scripts/build_prompts.py          write outputs
  python3 scripts/build_prompts.py --check  fail if outputs differ from the sources
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = ROOT / 'agent/prompts'
OPERATION_DOC = ROOT / 'docs/design/prompts/notebook-operation.md'
OPERATION_HEADING = '## 模型操作说明'
PLACEHOLDERS = {'{{version}}', '{{mode_line}}'}
MAX_ESTIMATED_TOKENS = 6000  # design 7.8; estimate is characters / 1.6

OUT_MD = PROMPTS / 'generated/system.zh.md'
OUT_JSON = PROMPTS / 'generated/prompt.json'
OUT_SWIFT = ROOT / 'macos/OpenMathNative/Agent/SystemPromptText.swift'


def read(name):
    return (PROMPTS / name).read_text(encoding='utf-8').strip()


def operation_guide():
    lines = OPERATION_DOC.read_text(encoding='utf-8').splitlines()
    try:
        start = lines.index(OPERATION_HEADING) + 1
    except ValueError:
        raise SystemExit(f'{OPERATION_DOC}: heading {OPERATION_HEADING!r} not found')
    end = next((i for i in range(start, len(lines)) if lines[i].startswith('## ')), len(lines))
    body = '\n'.join(lines[start:end]).strip()
    if not body or '1. ' not in body:
        raise SystemExit('operation guide section is empty or has no numbered rules')
    return body


def build():
    layers = [
        read('identity.zh.md'),
        '## 笔记本操作说明\n\n' + operation_guide(),
        read('language-card.zh.md'),
        read('examples.zh.md'),
        read('task-rules.zh.md'),
    ]
    template = '\n\n'.join(layers) + '\n'
    modes = {'execute': read('mode-exec.zh.md'), 'discuss': read('mode-discuss.zh.md')}
    found = set(re.findall(r'\{\{[a-z_]+\}\}', template))
    if found != PLACEHOLDERS:
        raise SystemExit(f'unexpected placeholders in template: {sorted(found ^ PLACEHOLDERS)}')
    for key, text in modes.items():
        if '{{' in text:
            raise SystemExit(f'mode line {key} contains a placeholder')
    chars = len(template)
    tokens = round(chars / 1.6)
    if tokens > MAX_ESTIMATED_TOKENS:
        raise SystemExit(f'system prompt too long: ~{tokens} tokens (limit {MAX_ESTIMATED_TOKENS}); trim examples first')
    digest = hashlib.sha256((template + '\n' + json.dumps(modes, ensure_ascii=False, sort_keys=True)).encode()).hexdigest()
    payload = {'template': template, 'modes': modes, 'sha256': digest, 'characters': chars, 'estimated_tokens': tokens}
    return template, payload


def swift_source(payload):
    def raw(text):
        if '"""' in text or '\\' in text:
            raise SystemExit('prompt text must not contain triple quotes or backslashes (raw string literal)')
        return '#"""\n' + text.rstrip('\n') + '\n"""#'
    return (
        '// Generated by scripts/build_prompts.py. Edit agent/prompts/*.md instead.\n'
        'enum SystemPromptText {\n'
        f'  static let sha256 = "{payload["sha256"]}"\n'
        f'  static let template = {raw(payload["template"])}\n'
        f'  static let modeExecute = {raw(payload["modes"]["execute"])}\n'
        f'  static let modeDiscuss = {raw(payload["modes"]["discuss"])}\n'
        '}\n'
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    template, payload = build()
    outputs = {
        OUT_MD: template,
        OUT_JSON: json.dumps(payload, ensure_ascii=False, indent=1) + '\n',
        OUT_SWIFT: swift_source(payload),
    }
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            print('prompt outputs are stale (run scripts/build_prompts.py): ' + ', '.join(stale), file=sys.stderr)
            return 1
        print(f'prompt outputs match sources: {payload["characters"]} chars, ~{payload["estimated_tokens"]} tokens, sha256 {payload["sha256"][:12]}')
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
    print(f'wrote prompt outputs: {payload["characters"]} chars, ~{payload["estimated_tokens"]} tokens, sha256 {payload["sha256"][:12]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
